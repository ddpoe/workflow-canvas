def _lock_with(package: str = "", *, name: str = "", where: str = "dependencies",
               marker: str | None = None) -> str:
    """The fixture lock plus *package*, reached from the project by one edge.

    Args:
        package: A ``[[package]]`` block to add.
        name: The added package's name (the edge's target).
        where: ``dependencies``, or the group or extra the edge sits in.
        marker: The edge's marker, if any.
    """
    lock = (FIXTURES / "uv.lock").read_text(encoding="utf-8")
    if not package:
        return lock
    edge = f'{{ name = "{name}"' + (f', marker = "{marker}"' if marker else "") + " }"
    if where == "dependencies":
        lock = lock.replace(_ROOT_DEPS_END, f'    {{ name = "six" }},\n    {edge},\n]')
    else:
        anchor = _GROUP_ANCHORS[where]
        lock = lock.replace(anchor, f"{anchor}    {edge},\n")
    return lock + "\n" + package


def _uv_project(root: Path, lock: str,
                python_version: str | dict | None = "3.12\n") -> Path:
    """Write a uv project (pyproject, lock, .python-version) under *root*.

    A dict *python_version* names files to make directories instead, so
    reading them fails (``.python-version`` is then otherwise ``3.12``).
    """
    project = root / "uvproj"
    project.mkdir(parents=True)
    shutil.copy(FIXTURES / "pyproject.toml", project / "pyproject.toml")
    (project / "uv.lock").write_text(lock, encoding="utf-8")
    unreadable = python_version if isinstance(python_version, dict) else {}
    if unreadable:
        python_version = "3.12\n"
    if python_version is not None:
        (project / ".python-version").write_text(python_version, encoding="utf-8")
    for name in unreadable:
        (project / name).unlink()
        (project / name).mkdir()
    return project


def _recording_export(calls: list, stdout: str = EXPORTED):
    """A `uv export` handler that records argv and cwd and prints *stdout*."""
    def handler(cmd, *args, **kwargs):
        calls.append({"argv": list(cmd), "cwd": Path(kwargs["cwd"])})
        return subprocess.CompletedProcess(cmd, 0, stdout=stdout, stderr="")
    return handler


@workflow(purpose="A uv project's capture runs `uv export --frozen --no-dev "
                  "--no-default-groups` in the project with each --group and "
                  "--extra; its stdout is the staged requirements and the "
                  "groups, extras and Python minor go into the source payload")
def test_the_export_carries_no_dev_the_groups_and_the_extras(tmp_path, monkeypatch):
    project = _uv_project(tmp_path, _lock_with())
    stub_binary_lookup(monkeypatch, uv=UV_ON_PATH)
    calls: list = []
    fake_subprocess_run(monkeypatch, _recording_export(calls), only="uv")

    capture = uv.capture_project(project / "uv.lock", groups=["docs"],
                                 extras=["plot"])

    assert calls == [{
        "argv": ["uv", "export", "--frozen", "--format", "requirements-txt",
                 "--no-emit-project", "--no-emit-workspace", "--no-dev",
                 "--no-default-groups", "--group", "docs", "--extra", "plot"],
        "cwd": project,
    }]
    assert capture.source == {
        uv.REQUIREMENTS_SOURCE_KEY: EXPORTED,
        "pip_freeze_content": "",
        uv.PYTHON_MINOR_SOURCE_KEY: "3.12",
        uv.GROUPS_SOURCE_KEY: ["docs"],
        uv.EXTRAS_SOURCE_KEY: ["plot"],
    }
    assert capture.warnings == ()

    # The project directory names the same project as its uv.lock.
    assert uv.capture_project(project, groups=["docs"],
                              extras=["plot"]).source == capture.source
    assert calls[1]["cwd"] == project


