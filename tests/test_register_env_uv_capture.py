@pytest.mark.parametrize("pin", ["3.12", "cp3.12", "cpython3.12", "cpython@3.12",
                                 "cpython-3.12"])
def test_python_minor_reads_uv_cpython_shorthands_as_cpython(tmp_path, pin):
    """uv's CPython spellings of a pin (``cp3.12``, ``cpython3.12``,
    ``cpython@3.12``) are read as CPython 3.12."""
    (tmp_path / uv.PYTHON_VERSION_FILENAME).write_text(pin + "\n", encoding="utf-8")

    assert uv.python_minor(tmp_path) == "3.12"


@pytest.mark.parametrize("pin", ["pypy3.10", "graalpy3.11", "pp3.10"])
def test_python_minor_still_refuses_other_implementations(tmp_path, pin):
    """A pin naming any implementation other than CPython is refused."""
    (tmp_path / uv.PYTHON_VERSION_FILENAME).write_text(pin + "\n", encoding="utf-8")

    with pytest.raises(uv.UvRefusal, match="CPython 3.10-3.13"):
        uv.python_minor(tmp_path)


@workflow(purpose="register-env --backend uv refuses before any Docker work and "
                  "before uv export: uv not on PATH, no .python-version (naming "
                  "`uv python pin 3.X`), a minor outside 3.10-3.13, a local, "
                  "editable or directory source, a hashless git or URL source, "
                  "and a package with no Linux wheel and no sdist, each named")
@pytest.mark.parametrize("binaries,lock,python_version,expected", _REFUSALS)
def test_a_uv_project_is_refused_before_docker(tmp_project, tmp_path, monkeypatch,
                                               capsys, binaries, lock,
                                               python_version, expected):
    project = _uv_project(tmp_path / "src", lock, python_version)
    stub_binary_lookup(monkeypatch, **{"uv": UV_ON_PATH, **binaries})
    fake_subprocess_run(monkeypatch, refusing_process("uv export ran"), only="uv")
