# ---- Tier 1: the lock walk evaluates one target --------------------------------

def test_the_lock_walk_follows_markers_groups_and_extras_for_one_target():
    """Only edges that hold on Linux x86_64 CPython 3.X, in the chosen groups
    and extras, reach the guard; an abi3 manylinux wheel installs."""
    # A darwin-only package with no Linux wheel is never installed.
    assert uv.check_lock(_lock_with(NO_LINUX_WHEEL, name="maconly",
                                    marker="sys_platform == 'darwin'"), "3.12") == ()
    # --no-dev: a git package in the dev group is not installed.
    assert uv.check_lock(_lock_with(GIT, name="gitpkg", where="dev"), "3.12") == ()
    # A group or an extra is walked only when chosen.
    in_docs = _lock_with(GIT, name="gitpkg", where="docs")
    assert uv.check_lock(in_docs, "3.12") == ()
    with pytest.raises(uv.UvRefusal, match="gitpkg"):
        uv.check_lock(in_docs, "3.12", groups=["docs"])
    in_plot = _lock_with(GIT, name="gitpkg", where="plot")
    assert uv.check_lock(in_plot, "3.12") == ()
    with pytest.raises(uv.UvRefusal, match="gitpkg"):
        uv.check_lock(in_plot, "3.12", extras=["plot"])
    # An abi3 wheel for an older CPython installs on 3.12.
    assert uv.check_lock(_lock_with(ABI3_WHEEL, name="abi3pkg"), "3.12") == ()
    # markupsafe 2.1.5 ships cp312 wheels only: on 3.13 it is sdist-only.
    warnings = uv.check_lock(_lock_with(), "3.13")
    assert len(warnings) == 1 and warnings[0].startswith("markupsafe 2.1.5")


def _hanging_process(cmd, *args, **kwargs):
    """A process that never ends: it stops only at the caller's timeout."""
    assert kwargs.get("timeout"), f"{cmd!r} ran with no timeout and would hang"
    raise subprocess.TimeoutExpired(cmd, kwargs["timeout"])


def test_a_uv_export_that_hangs_is_refused_naming_the_command(tmp_project, tmp_path,
                                                             monkeypatch, capsys):
    """`uv export` runs under a timeout; on expiry register-env refuses,
    naming the command, before Docker is asked."""
    project = _uv_project(tmp_path / "src", _lock_with())
    stub_binary_lookup(monkeypatch, uv=UV_ON_PATH)
    fake_subprocess_run(monkeypatch, _hanging_process, only="uv")
    asked: list = []

    rc = verbs.register_env("uvenv", backend="uv", from_path=str(project),
                            docker_gate=lambda: asked.append(1))

    err = capsys.readouterr().err
    assert rc == 1
    assert "uv export --frozen" in err and "did not finish" in err, err
    assert asked == []


